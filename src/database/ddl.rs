//! What a table is, written as SQL, and the rows it is linked to by its
//! foreign keys.

use super::designer::{list, parse_constraint};
use super::protocol::{quote_ident, quote_literal, Column, ConstraintKind, Reference, Structure};

/// The statements that make the table as it is: the table with its columns
/// and constraints, its indexes, its comments.
pub fn table_ddl(schema: &str, table: &str, s: &Structure) -> String {
    let name = format!("{}.{}", quote_ident(schema), quote_ident(table));
    let mut parts: Vec<String> = Vec::new();
    for c in &s.columns {
        let expression = c.default.as_deref().unwrap_or("");
        // A serial column owns its sequence: it is written as it was made, as the
        // sequence goes with the table.
        let serial = match c.kind.as_str() {
            "integer" => Some("serial"),
            "bigint" => Some("bigserial"),
            "smallint" => Some("smallserial"),
            _ => None,
        }
        .filter(|_| {
            !c.generated
                && c.identity.is_empty()
                && expression.starts_with("nextval(")
                && expression.contains(&format!("{table}_{}_seq", c.name))
        });
        let mut def = format!(
            "  {} {}",
            quote_ident(&c.name),
            serial.unwrap_or(c.kind.as_str())
        );
        if serial.is_some() {
            // Nothing more to say of the default.
        } else if c.generated {
            def.push_str(&format!(" GENERATED ALWAYS AS ({expression}) STORED"));
        } else if !c.identity.is_empty() {
            def.push_str(if c.identity == "a" {
                " GENERATED ALWAYS AS IDENTITY"
            } else {
                " GENERATED BY DEFAULT AS IDENTITY"
            });
        } else if !expression.is_empty() {
            def.push_str(&format!(" DEFAULT {expression}"));
        }
        if !c.nullable {
            def.push_str(" NOT NULL");
        }
        parts.push(def);
    }
    for c in &s.constraints {
        parts.push(format!(
            "  CONSTRAINT {} {}",
            quote_ident(&c.name),
            c.definition
        ));
    }
    let extra = &s.extra;
    let unlogged = if extra.unlogged { "UNLOGGED " } else { "" };
    let mut out = match &extra.partition_of {
        // A partition takes its columns from the table it belongs to.
        Some(of) => format!(
            "CREATE {unlogged}TABLE {name} PARTITION OF {}.{} {}{};\n",
            quote_ident(&of.schema),
            quote_ident(&of.table),
            of.bound,
            if extra.partition_key.is_empty() {
                String::new()
            } else {
                format!(" PARTITION BY {}", extra.partition_key)
            }
        ),
        None => format!(
            "CREATE {unlogged}TABLE {name} (\n{}\n){};\n",
            parts.join(",\n"),
            if extra.partition_key.is_empty() {
                String::new()
            } else {
                format!(" PARTITION BY {}", extra.partition_key)
            }
        ),
    };
    // The indexes of a partition come with its table.
    let indexes: &[_] = if extra.partition_of.is_some() {
        &[]
    } else {
        &s.indexes
    };
    if !indexes.is_empty() {
        out.push('\n');
        for i in indexes {
            out.push_str(&format!("{};\n", i.definition));
        }
    }
    if !extra.triggers.is_empty() {
        out.push('\n');
        for t in &extra.triggers {
            out.push_str(&format!("{t};\n"));
        }
    }
    let mut comments = Vec::new();
    if !s.comment.is_empty() {
        comments.push(format!(
            "COMMENT ON TABLE {name} IS {};",
            quote_literal(&s.comment)
        ));
    }
    for c in s.columns.iter().filter(|c| !c.comment.is_empty()) {
        comments.push(format!(
            "COMMENT ON COLUMN {name}.{} IS {};",
            quote_ident(&c.name),
            quote_literal(&c.comment)
        ));
    }
    if !comments.is_empty() {
        out.push('\n');
        out.push_str(&comments.join("\n"));
        out.push('\n');
    }
    out
}

/// A table made to be made again somewhere else: its columns, its keys and
/// checks, its indexes and its comments. Left out are what points to other
/// tables (a foreign key), triggers, and partitioning; a column that took its
/// values from a sequence gets an identity of its own.
pub fn portable(s: &Structure) -> Structure {
    let mut out = s.clone();
    out.extra = Default::default();
    out.referenced_by.clear();
    out.constraints
        .retain(|c| !matches!(c.kind, ConstraintKind::Foreign | ConstraintKind::Other));
    for c in &mut out.columns {
        let from_sequence = c
            .default
            .as_deref()
            .is_some_and(|d| d.starts_with("nextval("));
        let whole = matches!(c.kind.as_str(), "integer" | "bigint" | "smallint");
        if from_sequence {
            c.default = None;
            if whole && !c.generated {
                c.identity = "d".to_string();
            }
        }
        // To load the rows with the numbers they had, whatever the identity.
        if !c.identity.is_empty() {
            c.identity = "d".to_string();
        }
    }
    out
}

/// The statements that make a copy of a table: a schema if it is missing, the
/// table, then its indexes (named after the new table) and comments.
pub fn copy_statements(schema: &str, table: &str, s: &Structure) -> Vec<String> {
    let mut structure = portable(s);
    // An index is made again for the new table, under a name of its own.
    for index in &mut structure.indexes {
        index.definition = rename_index(&index.definition, schema, table);
    }
    let text = table_ddl(schema, table, &structure);
    let mut out = vec![format!(
        "CREATE SCHEMA IF NOT EXISTS {}",
        quote_ident(schema)
    )];
    out.extend(
        super::console::split_statements(&text)
            .into_iter()
            .map(|span| text[span.start..span.end].to_string()),
    );
    out
}

/// A `CREATE INDEX` that is for another table, under another name.
fn rename_index(definition: &str, schema: &str, table: &str) -> String {
    let pattern = regex::Regex::new(
        r#"^(CREATE (?:UNIQUE )?INDEX (?:CONCURRENTLY )?)("(?:[^"]|"")*"|\S+) ON (?:ONLY )?("(?:[^"]|"")*"|[^\s."]+)(?:\.("(?:[^"]|"")*"|[^\s."]+))? (.*)$"#,
    )
    .expect("a valid pattern");
    let Some(found) = pattern.captures(definition) else {
        return definition.to_string();
    };
    let unquote = |s: &str| {
        s.strip_prefix('"')
            .and_then(|s| s.strip_suffix('"'))
            .map_or_else(|| s.to_string(), |s| s.replace("\"\"", "\""))
    };
    // `schema.table`, or `table` alone when the schema is the default one.
    let old_index = unquote(&found[2]);
    let mut name = format!("{table}_{old_index}");
    if name.len() > 63 {
        let mut cut = 63;
        while !name.is_char_boundary(cut) {
            cut -= 1;
        }
        name.truncate(cut);
    }
    format!(
        "{}{} ON {}.{} {}",
        &found[1],
        quote_ident(&name),
        quote_ident(schema),
        quote_ident(table),
        &found[5]
    )
}

/// The statement that puts a sequence back where the rows are, after rows
/// were loaded with their own numbers.
pub fn restart_sequences(schema: &str, table: &str, s: &Structure) -> Vec<String> {
    let name = format!("{}.{}", quote_ident(schema), quote_ident(table));
    portable(s)
        .columns
        .iter()
        .filter(|c| !c.identity.is_empty())
        .map(|c| {
            let column = quote_ident(&c.name);
            format!(
                "SELECT setval(pg_get_serial_sequence({}, {}), COALESCE(MAX({column}), 1), MAX({column}) IS NOT NULL) FROM {name}",
                quote_literal(&name),
                quote_literal(&c.name)
            )
        })
        .collect()
}

/// Rows linked to a row: the table, and the condition that picks them.
#[derive(Debug, Clone, PartialEq)]
pub struct Link {
    /// The row points to them (`true`), or they point to the row.
    pub outgoing: bool,
    pub schema: String,
    pub table: String,
    pub filter: String,
    /// The columns and values that make the link, for the menu.
    pub label: String,
}

/// `schema.table` or `table`, without quotes.
fn qualified(text: &str) -> (Option<String>, String) {
    let mut parts: Vec<String> = Vec::new();
    let mut current = String::new();
    let mut quoted = false;
    for c in text.trim().chars() {
        match c {
            '"' => quoted = !quoted,
            '.' if !quoted => parts.push(std::mem::take(&mut current)),
            c => current.push(c),
        }
    }
    parts.push(current);
    let table = parts.pop().unwrap_or_default();
    (parts.pop(), table)
}

/// The condition on `columns` of a table that the values `values` make.
fn condition(columns: &[String], values: &[String]) -> String {
    columns
        .iter()
        .zip(values)
        .map(|(c, v)| format!("{} = {}", quote_ident(c), quote_literal(v)))
        .collect::<Vec<_>>()
        .join(" AND ")
}

/// The values of a row in the named columns; none if one is missing or null.
fn values_of(names: &[String], columns: &[Column], row: &[Option<String>]) -> Option<Vec<String>> {
    names
        .iter()
        .map(|name| {
            let at = columns.iter().position(|c| c.name == *name)?;
            row.get(at)?.clone()
        })
        .collect()
}

/// The rows a row is linked to: the ones its foreign keys point to, and the
/// ones whose foreign keys point to it.
pub fn links(schema: &str, s: &Structure, columns: &[Column], row: &[Option<String>]) -> Vec<Link> {
    let mut out = Vec::new();
    for c in s
        .constraints
        .iter()
        .filter(|c| c.kind == ConstraintKind::Foreign)
    {
        let Some(p) = parse_constraint(c.kind, &c.definition) else {
            continue;
        };
        let (own, theirs) = (list(&p.columns), list(&p.ref_columns));
        if own.is_empty() || own.len() != theirs.len() {
            continue;
        }
        let Some(values) = values_of(&own, columns, row) else {
            continue;
        };
        let (target_schema, table) = qualified(&p.reference);
        out.push(Link {
            outgoing: true,
            schema: target_schema.unwrap_or_else(|| schema.to_string()),
            table,
            filter: condition(&theirs, &values),
            label: condition(&own, &values),
        });
    }
    for Reference {
        schema: from_schema,
        table,
        definition,
        ..
    } in &s.referenced_by
    {
        let Some(p) = parse_constraint(ConstraintKind::Foreign, definition) else {
            continue;
        };
        // Their columns point to ours.
        let (theirs, own) = (list(&p.columns), list(&p.ref_columns));
        if own.is_empty() || own.len() != theirs.len() {
            continue;
        }
        let Some(values) = values_of(&own, columns, row) else {
            continue;
        };
        out.push(Link {
            outgoing: false,
            schema: from_schema.clone(),
            table: table.clone(),
            filter: condition(&theirs, &values),
            label: condition(&own, &values),
        });
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::database::protocol::{ColumnDef, ConstraintDef, IndexDef};

    fn col(name: &str, kind: &str, nullable: bool) -> ColumnDef {
        ColumnDef {
            name: name.into(),
            kind: kind.into(),
            nullable,
            default: None,
            identity: String::new(),
            generated: false,
            comment: String::new(),
        }
    }

    fn structure() -> Structure {
        let mut id = col("id", "integer", false);
        id.identity = "a".into();
        let mut total = col("total", "numeric(10,2)", false);
        total.default = Some("0".into());
        total.comment = "what's due".into();
        let mut tax = col("tax", "numeric", true);
        tax.generated = true;
        tax.default = Some("total * 0.2".into());
        Structure {
            columns: vec![id, col("customer_id", "integer", true), total, tax],
            constraints: vec![
                ConstraintDef {
                    name: "orders_pkey".into(),
                    kind: ConstraintKind::Primary,
                    definition: "PRIMARY KEY (id)".into(),
                },
                ConstraintDef {
                    name: "orders_customer_fkey".into(),
                    kind: ConstraintKind::Foreign,
                    definition: "FOREIGN KEY (customer_id) REFERENCES sales.customers(id)".into(),
                },
            ],
            indexes: vec![IndexDef {
                name: "orders_customer_idx".into(),
                definition:
                    "CREATE INDEX orders_customer_idx ON public.orders USING btree (customer_id)"
                        .into(),
                unique: false,
            }],
            comment: "the orders".into(),
            referenced_by: vec![Reference {
                name: "lines_order_fkey".into(),
                schema: "public".into(),
                table: "order lines".into(),
                definition: "FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE".into(),
            }],
            ..Default::default()
        }
    }

    #[test]
    fn a_partitioned_table_a_partition_and_a_trigger_are_written_as_they_are() {
        use super::super::protocol::{PartitionOf, TableExtra};
        let mut s = Structure {
            columns: vec![col("at", "date", false)],
            extra: Box::new(TableExtra {
                partition_key: "RANGE (at)".into(),
                triggers: vec![
                    "CREATE TRIGGER t BEFORE INSERT ON public.log FOR EACH ROW EXECUTE FUNCTION f()"
                        .into(),
                ],
                unlogged: true,
                ..Default::default()
            }),
            ..Default::default()
        };
        let parent = table_ddl("public", "log", &s);
        assert!(parent.starts_with("CREATE UNLOGGED TABLE \"public\".\"log\" (\n  \"at\" date NOT NULL\n) PARTITION BY RANGE (at);"), "{parent}");
        assert!(parent.contains("CREATE TRIGGER t BEFORE INSERT"));
        s.extra.partition_key.clear();
        s.extra.partition_of = Some(PartitionOf {
            schema: "public".into(),
            table: "log".into(),
            bound: "FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')".into(),
        });
        let child = table_ddl("public", "log_2026", &s);
        assert!(child.starts_with("CREATE UNLOGGED TABLE \"public\".\"log_2026\" PARTITION OF \"public\".\"log\" FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');"), "{child}");
    }

    #[test]
    fn the_ddl_makes_the_table_as_it_is() {
        assert_eq!(
            table_ddl("public", "orders", &structure()),
            "CREATE TABLE \"public\".\"orders\" (\n  \"id\" integer GENERATED ALWAYS AS IDENTITY NOT NULL,\n  \"customer_id\" integer,\n  \"total\" numeric(10,2) DEFAULT 0 NOT NULL,\n  \"tax\" numeric GENERATED ALWAYS AS (total * 0.2) STORED,\n  CONSTRAINT \"orders_pkey\" PRIMARY KEY (id),\n  CONSTRAINT \"orders_customer_fkey\" FOREIGN KEY (customer_id) REFERENCES sales.customers(id)\n);\n\nCREATE INDEX orders_customer_idx ON public.orders USING btree (customer_id);\n\nCOMMENT ON TABLE \"public\".\"orders\" IS 'the orders';\nCOMMENT ON COLUMN \"public\".\"orders\".\"total\" IS 'what''s due';\n"
        );
    }

    #[test]
    fn a_serial_column_is_written_as_serial() {
        let mut id = col("id", "integer", false);
        id.default = Some("nextval('orders_id_seq'::regclass)".into());
        let mut big = col("n", "bigint", false);
        big.default = Some("nextval('other_seq'::regclass)".into());
        let s = Structure {
            columns: vec![id, big],
            ..Default::default()
        };
        let text = table_ddl("public", "orders", &s);
        assert!(text.contains("\"id\" serial NOT NULL"), "{text}");
        // A sequence of its own is not made again: the default stays.
        assert!(text.contains("\"n\" bigint DEFAULT nextval('other_seq'::regclass) NOT NULL"));
    }

    #[test]
    fn a_row_is_linked_to_what_it_points_to_and_to_what_points_to_it() {
        let s = structure();
        let columns: Vec<Column> = s
            .columns
            .iter()
            .map(|c| Column {
                name: c.name.clone(),
                kind: c.kind.clone(),
                nullable: c.nullable,
            })
            .collect();
        let row = vec![
            Some("7".to_string()),
            Some("42".to_string()),
            Some("9.50".to_string()),
            None,
        ];
        let found = links("public", &s, &columns, &row);
        assert_eq!(found.len(), 2);
        assert_eq!(
            found[0],
            Link {
                outgoing: true,
                schema: "sales".into(),
                table: "customers".into(),
                filter: "\"id\" = '42'".into(),
                label: "\"customer_id\" = '42'".into(),
            }
        );
        // What points to the row is found by the row's own key.
        assert_eq!(
            found[1],
            Link {
                outgoing: false,
                schema: "public".into(),
                table: "order lines".into(),
                filter: "\"order_id\" = '7'".into(),
                label: "\"id\" = '7'".into(),
            }
        );
        // A null key links to nothing.
        let mut row = row;
        row[1] = None;
        let found = links("public", &s, &columns, &row);
        assert_eq!(found.len(), 1);
        assert!(!found[0].outgoing);
    }

    #[test]
    fn a_name_is_cut_at_its_dots_outside_quotes() {
        assert_eq!(qualified("customers"), (None, "customers".into()));
        assert_eq!(
            qualified("sales.\"Order. Items\""),
            (Some("sales".into()), "Order. Items".into())
        );
    }

    #[test]
    fn a_copy_leaves_out_what_points_elsewhere_and_gives_sequences_an_identity() {
        let mut s = Structure {
            columns: vec![col("id", "integer", false), col("owner", "integer", true)],
            ..Structure::default()
        };
        s.columns[0].default = Some("nextval('old_id_seq'::regclass)".into());
        s.constraints = vec![
            ConstraintDef {
                name: "old_pkey".into(),
                kind: ConstraintKind::Primary,
                definition: "PRIMARY KEY (id)".into(),
            },
            ConstraintDef {
                name: "old_owner_fkey".into(),
                kind: ConstraintKind::Foreign,
                definition: "FOREIGN KEY (owner) REFERENCES users(id)".into(),
            },
        ];
        s.extra.triggers =
            vec!["CREATE TRIGGER t BEFORE INSERT ON old FOR EACH ROW EXECUTE FUNCTION f()".into()];
        let p = portable(&s);
        assert_eq!(p.columns[0].default, None);
        assert_eq!(p.columns[0].identity, "d");
        assert_eq!(p.constraints.len(), 1);
        assert!(p.extra.triggers.is_empty());
        let statements = copy_statements("copy", "new", &s);
        assert_eq!(statements[0], "CREATE SCHEMA IF NOT EXISTS \"copy\"");
        assert!(statements[1].starts_with("CREATE TABLE \"copy\".\"new\" ("));
        assert!(statements[1].contains("\"id\" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL"));
        assert!(!statements.join("\n").contains("REFERENCES"));
        assert!(!statements.join("\n").contains("TRIGGER"));
        // An identity that is always generated is loaded by default.
        let mut always = s.clone();
        always.columns[1].identity = "a".into();
        assert_eq!(portable(&always).columns[1].identity, "d");
    }

    #[test]
    fn an_index_is_made_again_for_the_new_table_under_its_own_name() {
        let old = "CREATE UNIQUE INDEX items_label_idx ON public.items USING btree (label)";
        assert_eq!(
            rename_index(old, "copy", "items2"),
            "CREATE UNIQUE INDEX \"items2_items_label_idx\" ON \"copy\".\"items2\" USING btree (label)"
        );
        // Quoted names, and a table without its schema.
        let quoted = "CREATE INDEX \"My Idx\" ON \"Sales\".\"Order Items\" USING gin (tags)";
        assert_eq!(
            rename_index(quoted, "s", "t"),
            "CREATE INDEX \"t_My Idx\" ON \"s\".\"t\" USING gin (tags)"
        );
        // Something that is not an index is left as it is.
        assert_eq!(rename_index("nonsense", "s", "t"), "nonsense");
        // A long name is cut to what PostgreSQL keeps.
        let long = format!(
            "CREATE INDEX {} ON public.t USING btree (a)",
            "x".repeat(60)
        );
        let out = rename_index(&long, "s", "table_name");
        let name = out.split('"').nth(1).unwrap();
        assert!(name.len() <= 63, "{}", name.len());
    }

    #[test]
    fn the_sequences_of_a_copy_are_put_back_where_the_rows_are() {
        let mut s = Structure {
            columns: vec![col("id", "integer", false), col("n", "text", true)],
            ..Structure::default()
        };
        s.columns[0].identity = "a".into();
        let sql = restart_sequences("s", "t", &s);
        assert_eq!(sql.len(), 1);
        assert!(sql[0].starts_with("SELECT setval(pg_get_serial_sequence('\"s\".\"t\"', 'id')"));
        assert!(sql[0].ends_with("FROM \"s\".\"t\""));
        // No identity, nothing to restart.
        s.columns[0].identity.clear();
        assert!(restart_sequences("s", "t", &s).is_empty());
    }
}
