//! What a table is, written as SQL, and the rows it is linked to by its
//! foreign keys.

use super::designer::{list, parse_constraint};
use super::protocol::{quote_ident, quote_literal, Column, ConstraintKind, Reference, Structure};

/// The statements that make the table as it is: the table with its columns
/// and constraints, its indexes, its comments.
pub fn table_ddl(schema: &str, table: &str, s: &Structure) -> String {
    let name = format!("{}.{}", quote_ident(schema), quote_ident(table));
    let mut parts: Vec<String> = Vec::new();
    for c in &s.columns {
        let expression = c.default.as_deref().unwrap_or("");
        // A serial column owns its sequence: it is written as it was made, as the
        // sequence goes with the table.
        let serial = match c.kind.as_str() {
            "integer" => Some("serial"),
            "bigint" => Some("bigserial"),
            "smallint" => Some("smallserial"),
            _ => None,
        }
        .filter(|_| {
            !c.generated
                && c.identity.is_empty()
                && expression.starts_with("nextval(")
                && expression.contains(&format!("{table}_{}_seq", c.name))
        });
        let mut def = format!(
            "  {} {}",
            quote_ident(&c.name),
            serial.unwrap_or(c.kind.as_str())
        );
        if serial.is_some() {
            // Nothing more to say of the default.
        } else if c.generated {
            def.push_str(&format!(" GENERATED ALWAYS AS ({expression}) STORED"));
        } else if !c.identity.is_empty() {
            def.push_str(if c.identity == "a" {
                " GENERATED ALWAYS AS IDENTITY"
            } else {
                " GENERATED BY DEFAULT AS IDENTITY"
            });
        } else if !expression.is_empty() {
            def.push_str(&format!(" DEFAULT {expression}"));
        }
        if !c.nullable {
            def.push_str(" NOT NULL");
        }
        parts.push(def);
    }
    for c in &s.constraints {
        parts.push(format!(
            "  CONSTRAINT {} {}",
            quote_ident(&c.name),
            c.definition
        ));
    }
    let mut out = format!("CREATE TABLE {name} (\n{}\n);\n", parts.join(",\n"));
    if !s.indexes.is_empty() {
        out.push('\n');
        for i in &s.indexes {
            out.push_str(&format!("{};\n", i.definition));
        }
    }
    let mut comments = Vec::new();
    if !s.comment.is_empty() {
        comments.push(format!(
            "COMMENT ON TABLE {name} IS {};",
            quote_literal(&s.comment)
        ));
    }
    for c in s.columns.iter().filter(|c| !c.comment.is_empty()) {
        comments.push(format!(
            "COMMENT ON COLUMN {name}.{} IS {};",
            quote_ident(&c.name),
            quote_literal(&c.comment)
        ));
    }
    if !comments.is_empty() {
        out.push('\n');
        out.push_str(&comments.join("\n"));
        out.push('\n');
    }
    out
}

/// Rows linked to a row: the table, and the condition that picks them.
#[derive(Debug, Clone, PartialEq)]
pub struct Link {
    /// The row points to them (`true`), or they point to the row.
    pub outgoing: bool,
    pub schema: String,
    pub table: String,
    pub filter: String,
    /// The columns and values that make the link, for the menu.
    pub label: String,
}

/// `schema.table` or `table`, without quotes.
fn qualified(text: &str) -> (Option<String>, String) {
    let mut parts: Vec<String> = Vec::new();
    let mut current = String::new();
    let mut quoted = false;
    for c in text.trim().chars() {
        match c {
            '"' => quoted = !quoted,
            '.' if !quoted => parts.push(std::mem::take(&mut current)),
            c => current.push(c),
        }
    }
    parts.push(current);
    let table = parts.pop().unwrap_or_default();
    (parts.pop(), table)
}

/// The condition on `columns` of a table that the values `values` make.
fn condition(columns: &[String], values: &[String]) -> String {
    columns
        .iter()
        .zip(values)
        .map(|(c, v)| format!("{} = {}", quote_ident(c), quote_literal(v)))
        .collect::<Vec<_>>()
        .join(" AND ")
}

/// The values of a row in the named columns; none if one is missing or null.
fn values_of(names: &[String], columns: &[Column], row: &[Option<String>]) -> Option<Vec<String>> {
    names
        .iter()
        .map(|name| {
            let at = columns.iter().position(|c| c.name == *name)?;
            row.get(at)?.clone()
        })
        .collect()
}

/// The rows a row is linked to: the ones its foreign keys point to, and the
/// ones whose foreign keys point to it.
pub fn links(schema: &str, s: &Structure, columns: &[Column], row: &[Option<String>]) -> Vec<Link> {
    let mut out = Vec::new();
    for c in s
        .constraints
        .iter()
        .filter(|c| c.kind == ConstraintKind::Foreign)
    {
        let Some(p) = parse_constraint(c.kind, &c.definition) else {
            continue;
        };
        let (own, theirs) = (list(&p.columns), list(&p.ref_columns));
        if own.is_empty() || own.len() != theirs.len() {
            continue;
        }
        let Some(values) = values_of(&own, columns, row) else {
            continue;
        };
        let (target_schema, table) = qualified(&p.reference);
        out.push(Link {
            outgoing: true,
            schema: target_schema.unwrap_or_else(|| schema.to_string()),
            table,
            filter: condition(&theirs, &values),
            label: condition(&own, &values),
        });
    }
    for Reference {
        schema: from_schema,
        table,
        definition,
        ..
    } in &s.referenced_by
    {
        let Some(p) = parse_constraint(ConstraintKind::Foreign, definition) else {
            continue;
        };
        // Their columns point to ours.
        let (theirs, own) = (list(&p.columns), list(&p.ref_columns));
        if own.is_empty() || own.len() != theirs.len() {
            continue;
        }
        let Some(values) = values_of(&own, columns, row) else {
            continue;
        };
        out.push(Link {
            outgoing: false,
            schema: from_schema.clone(),
            table: table.clone(),
            filter: condition(&theirs, &values),
            label: condition(&own, &values),
        });
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::database::protocol::{ColumnDef, ConstraintDef, IndexDef};

    fn col(name: &str, kind: &str, nullable: bool) -> ColumnDef {
        ColumnDef {
            name: name.into(),
            kind: kind.into(),
            nullable,
            default: None,
            identity: String::new(),
            generated: false,
            comment: String::new(),
        }
    }

    fn structure() -> Structure {
        let mut id = col("id", "integer", false);
        id.identity = "a".into();
        let mut total = col("total", "numeric(10,2)", false);
        total.default = Some("0".into());
        total.comment = "what's due".into();
        let mut tax = col("tax", "numeric", true);
        tax.generated = true;
        tax.default = Some("total * 0.2".into());
        Structure {
            columns: vec![id, col("customer_id", "integer", true), total, tax],
            constraints: vec![
                ConstraintDef {
                    name: "orders_pkey".into(),
                    kind: ConstraintKind::Primary,
                    definition: "PRIMARY KEY (id)".into(),
                },
                ConstraintDef {
                    name: "orders_customer_fkey".into(),
                    kind: ConstraintKind::Foreign,
                    definition: "FOREIGN KEY (customer_id) REFERENCES sales.customers(id)".into(),
                },
            ],
            indexes: vec![IndexDef {
                name: "orders_customer_idx".into(),
                definition:
                    "CREATE INDEX orders_customer_idx ON public.orders USING btree (customer_id)"
                        .into(),
                unique: false,
            }],
            comment: "the orders".into(),
            referenced_by: vec![Reference {
                name: "lines_order_fkey".into(),
                schema: "public".into(),
                table: "order lines".into(),
                definition: "FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE".into(),
            }],
        }
    }

    #[test]
    fn the_ddl_makes_the_table_as_it_is() {
        assert_eq!(
            table_ddl("public", "orders", &structure()),
            "CREATE TABLE \"public\".\"orders\" (\n  \"id\" integer GENERATED ALWAYS AS IDENTITY NOT NULL,\n  \"customer_id\" integer,\n  \"total\" numeric(10,2) DEFAULT 0 NOT NULL,\n  \"tax\" numeric GENERATED ALWAYS AS (total * 0.2) STORED,\n  CONSTRAINT \"orders_pkey\" PRIMARY KEY (id),\n  CONSTRAINT \"orders_customer_fkey\" FOREIGN KEY (customer_id) REFERENCES sales.customers(id)\n);\n\nCREATE INDEX orders_customer_idx ON public.orders USING btree (customer_id);\n\nCOMMENT ON TABLE \"public\".\"orders\" IS 'the orders';\nCOMMENT ON COLUMN \"public\".\"orders\".\"total\" IS 'what''s due';\n"
        );
    }

    #[test]
    fn a_serial_column_is_written_as_serial() {
        let mut id = col("id", "integer", false);
        id.default = Some("nextval('orders_id_seq'::regclass)".into());
        let mut big = col("n", "bigint", false);
        big.default = Some("nextval('other_seq'::regclass)".into());
        let s = Structure {
            columns: vec![id, big],
            ..Default::default()
        };
        let text = table_ddl("public", "orders", &s);
        assert!(text.contains("\"id\" serial NOT NULL"), "{text}");
        // A sequence of its own is not made again: the default stays.
        assert!(text.contains("\"n\" bigint DEFAULT nextval('other_seq'::regclass) NOT NULL"));
    }

    #[test]
    fn a_row_is_linked_to_what_it_points_to_and_to_what_points_to_it() {
        let s = structure();
        let columns: Vec<Column> = s
            .columns
            .iter()
            .map(|c| Column {
                name: c.name.clone(),
                kind: c.kind.clone(),
                nullable: c.nullable,
            })
            .collect();
        let row = vec![
            Some("7".to_string()),
            Some("42".to_string()),
            Some("9.50".to_string()),
            None,
        ];
        let found = links("public", &s, &columns, &row);
        assert_eq!(found.len(), 2);
        assert_eq!(
            found[0],
            Link {
                outgoing: true,
                schema: "sales".into(),
                table: "customers".into(),
                filter: "\"id\" = '42'".into(),
                label: "\"customer_id\" = '42'".into(),
            }
        );
        // What points to the row is found by the row's own key.
        assert_eq!(
            found[1],
            Link {
                outgoing: false,
                schema: "public".into(),
                table: "order lines".into(),
                filter: "\"order_id\" = '7'".into(),
                label: "\"id\" = '7'".into(),
            }
        );
        // A null key links to nothing.
        let mut row = row;
        row[1] = None;
        let found = links("public", &s, &columns, &row);
        assert_eq!(found.len(), 1);
        assert!(!found[0].outgoing);
    }

    #[test]
    fn a_name_is_cut_at_its_dots_outside_quotes() {
        assert_eq!(qualified("customers"), (None, "customers".into()));
        assert_eq!(
            qualified("sales.\"Order. Items\""),
            (Some("sales".into()), "Order. Items".into())
        );
    }
}
